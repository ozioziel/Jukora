import { type ResourcePlan, type SearchRequest } from '@jucumari/shared';
import type { ResourcePlanner } from './planner';

type Sector = 'restaurant' | 'cafe' | 'workshop' | 'store' | 'studio' | 'other';
type Res = ResourcePlan['resources'][number];

const SECTOR_PATTERNS: [Sector, RegExp][] = [
  ['cafe', /caf[eé]|cafeter|coffee|barista/i],
  ['restaurant', /hamburgues|burger|restaur|comida|taquer|taco|pizz|pollo|cocina|food|parrill/i],
  ['workshop', /taller|workshop|mec[aá]nic|carpinter|solda|metal|weld/i],
  ['studio', /estudio|studio|audiovisual|fotogr|video|podcast|grabaci/i],
  ['store', /tienda|store|minimarket|boutique|almac[eé]n|shop/i],
];

export function detectSector(text: string): Sector {
  return SECTOR_PATTERNS.find(([, re]) => re.test(text))?.[0] ?? 'other';
}

const L = (es: string, en: string, locale: SearchRequest['locale']) => (locale === 'en' ? en : es);

function r(
  id: string,
  label: string,
  category: string,
  quantity: number | null,
  unit: string,
  reason: string,
  terms: string[],
  priority: Res['priority'],
  specs: string[] = [],
): Res {
  return {
    id,
    label,
    category,
    quantity,
    unit,
    reason,
    requiredSpecs: specs,
    optionalSpecs: [],
    searchTerms: terms,
    dependencies: [],
    priority,
    estimatedCost: null,
  };
}

